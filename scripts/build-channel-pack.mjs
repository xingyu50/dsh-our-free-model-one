/**
 * Bundle the vendored free-channel pack into one file.
 *
 *     node scripts/build-channel-pack.mjs
 *
 * `vendor/channel-pack/src/**` is the tracked source of the absorbed plugin
 * (provenance in vendor/channel-pack/NOTICE.md). Shipping it as a tree would put
 * ~360 files in the release manifest, and the manifest refuses more than 80 —
 * a cap that exists so an upgrade cannot become an unbounded download. So the
 * pack is bundled instead: `vendor/channel-pack/pack.js` plus the Qoder WASM it
 * loads beside itself.
 *
 * What stays external, and why:
 * - `@deepseek-ai/*` — host-provided. The pack must share the running kernel's
 *   own instances (cordis contexts, the llm registry), so bundling a second
 *   copy would break identity checks, not just bloat the file.
 * - `node:*` — platform builtins.
 * Everything else (`undici`) is inlined, which is what lets the package
 * stay self-contained without vendoring node_modules.
 *
 * Run after editing/re-vendoring `src/`; requires esbuild (devDependency, or any
 * checkout that has it on the resolution path).
 */
import { readFileSync, writeFileSync, statSync, existsSync, rmSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { publishedBytes } from './lib/published-bytes.mjs'

const root = path.join(fileURLToPath(new URL('..', import.meta.url)))
const packDir = path.join(root, 'vendor', 'channel-pack')
const entry = path.join(packDir, 'src', 'index.ts')
const outfile = path.join(packDir, 'pack.js')

// --check answers one question: is the committed bundle what this source builds?
// Without it the bundle was the only shipped file with no machine-checkable tie to
// its input — `npm run channel-pack` always rewrote it, so "did I forget to
// rebuild?" had no answer short of reading the diff. Measured cost of the extra
// build: ~150 ms.
//
// It builds to a temporary file instead of using `write:false`: measured on this
// tree, esbuild's in-memory output was 266 bytes shorter than the file it writes
// for the same config, so comparing those two would report drift on a correct tree.
const checkMode = process.argv.includes('--check')
const buildTarget = checkMode ? path.join(os.tmpdir(), 'ofm-pack-check-' + process.pid + '.js') : outfile

// Removed on every way out, including the ones that throw: an rm beside each
// process.exit() left a 2.8 MiB file behind whenever the build or the read after
// it failed. The name carries the pid so parallel runs cannot collide.
if (checkMode) {
  process.on('exit', () => {
    try { rmSync(buildTarget, { force: true }) } catch { /* the temp file is worth less than the exit code */ }
  })
}

let esbuild
try {
  // Resolved through CJS resolution so NODE_PATH and an explicit
  // OFM_ESBUILD_DIR both work: ESM `import` ignores NODE_PATH, and a
  // re-vendoring session usually has esbuild in a sibling checkout rather than
  // in this package.
  const { createRequire } = await import('node:module')
  const require = createRequire(import.meta.url)
  const candidates = [process.env.OFM_ESBUILD_DIR, process.cwd(), root].filter(Boolean)
  const resolved = require.resolve('esbuild', { paths: candidates })
  esbuild = await import(pathToFileURL(resolved).href)
} catch (error) {
  console.error('build-channel-pack: esbuild is required to rebuild the pack.')
  console.error('  install it (npm i -D esbuild), or point OFM_ESBUILD_DIR at a directory that has it.')
  console.error(`  (${error?.message ?? error})`)
  process.exit(1)
}

const result = await esbuild.build({
  entryPoints: [entry],
  outfile: buildTarget,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: ['node22'],
  // The kernel's own modules must resolve at run time, to the host's copies.
  external: ['@deepseek-ai/*', 'node:*'],
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
  // The pack is ESM with dynamic `import('./login.js')` for browser-opening
  // helpers; without splitting esbuild inlines those as already-resolved
  // promises, which is what a single-file bundle needs.
  splitting: false,
  banner: {
    js: [
      '// Generated by scripts/build-channel-pack.mjs — do not edit.',
      '// Source: vendor/channel-pack/src (the absorbed free-channel pack; see NOTICE.md).',
      // Bundled CJS dependencies (undici in particular) call require() for node
      // builtins. In an ESM bundle esbuild routes those through a helper that
      // throws "Dynamic require of ... is not supported" unless a real `require`
      // is in scope — measured: the pack failed to mount with exactly that error
      // for node:assert. createRequire supplies one; the helper prefers it
      // because it checks `typeof require !== "undefined"` first.
      "import { createRequire as __ofmCreateRequire } from 'node:module'",
      'const require = __ofmCreateRequire(import.meta.url)',
    ].join('\n'),
  },
})

// A bundle that silently lost its entry would still be a valid file, so the
// build states its size instead of trusting the exit code alone. In --check mode
// this also guards the comparison below: an empty or banner-less build would
// otherwise be reported as "drift" instead of as a broken build.
const bytes = statSync(buildTarget).size
const head = readFileSync(buildTarget, 'utf8').slice(0, 400)
if (!head.includes('Generated by scripts/build-channel-pack.mjs')) {
  console.error('build-channel-pack: the bundle lost its banner — refusing to call this a success')
  process.exit(1)
}

if (checkMode) {
  const built = readFileSync(buildTarget)
  // Compared in the bytes a user receives, not the bytes on this disk:
  // `.gitattributes` says `eol=lf`, so a CRLF working tree (a Windows checkout
  // with core.autocrlf=true) holds a file a few hundred bytes longer than the one
  // that downloads. build-manifest.mjs and catalog-test.mjs normalise through this
  // helper for the same reason — without it the manifest check passes and this one
  // reports "built from older sources", which is the wrong diagnosis.
  const committedRaw = existsSync(outfile) ? readFileSync(outfile) : undefined
  const committed = committedRaw === undefined ? undefined : publishedBytes(committedRaw)
  const builtBytes = publishedBytes(built)
  if (committed === undefined) {
    console.error(`build-channel-pack: ${path.relative(root, outfile)} does not exist — every install would ship a pack built from nothing`)
    console.error('run: npm run channel-pack, then npm run build:standalone-channels')
    process.exit(1)
  }
  if (Buffer.compare(builtBytes, committed) !== 0) {
    console.error(`build-channel-pack: ${path.relative(root, outfile)} does not match vendor/channel-pack/src`)
    console.error(`  ${committed.length} bytes committed, ${builtBytes.length} bytes from source`)
    console.error('every user would install a bundle built from older sources')
    console.error('  contributors: npm run generated:check')
    console.error('  maintainers: OFM_MANIFEST_KEY=<key> npm run regen (the manifest step refuses to sign without it)')
    process.exit(1)
  }
  console.log(`build-channel-pack: ${path.relative(root, outfile)} matches vendor/channel-pack/src (${(builtBytes.length / 1024 / 1024).toFixed(2)} MiB)`)
  if (result.warnings.length > 0) {
    console.log(`build-channel-pack: ${result.warnings.length} warning(s)`)
  }
  process.exit(0)
}

console.log(`build-channel-pack: wrote ${path.relative(root, outfile)} (${(bytes / 1024 / 1024).toFixed(2)} MiB)`)
if (result.warnings.length > 0) {
  console.log(`build-channel-pack: ${result.warnings.length} warning(s)`)
}
